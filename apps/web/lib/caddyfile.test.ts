import assert from 'node:assert/strict';
import {
  generateSiteBlock,
  validateServiceInput,
  availableTlsModes,
  getDefaultTlsMode,
  validateTlsModeConfigured,
  ValidationError,
  type CaddyfileService,
  type TlsMode,
} from './caddyfile';

let passed = 0;
let failed = 0;

function test(name: string, fn: () => void) {
  try {
    fn();
    passed++;
    console.log(`  ✓ ${name}`);
  } catch (err: unknown) {
    failed++;
    console.error(`  ✗ ${name}`);
    console.error(`    ${err instanceof Error ? err.message : String(err)}`);
  }
}

function proxyService(overrides: Partial<CaddyfileService> = {}): CaddyfileService {
  return {
    id: 'cmabc123',
    domains: ['piren.org', 'www.piren.org'],
    upstreamContainer: 'piren_app',
    upstreamPort: 3000,
    tlsMode: 'acme' as TlsMode,
    serviceType: 'proxy',
    staticRoot: null,
    ...overrides,
  };
}

function staticService(overrides: Partial<CaddyfileService> = {}): CaddyfileService {
  return {
    id: 'cmxyz789',
    domains: ['landing.staging.lucchesi.io'],
    upstreamContainer: null,
    upstreamPort: null,
    tlsMode: 'namecheap_tls' as TlsMode,
    serviceType: 'static',
    staticRoot: '/srv/sites/landing.staging.lucchesi.io',
    ...overrides,
  };
}

// ── Proxy block generation ──────────────────────────────────────

console.log('\n# Proxy block generation');

test('generates valid proxy block', () => {
  const svc = proxyService();
  const output = generateSiteBlock(svc);
  assert.ok(output.includes('# Generated by Portcullis. Do not edit manually.'));
  assert.ok(output.includes('# Service ID: cmabc123'));
  assert.ok(output.includes('# Domains: piren.org, www.piren.org'));
  assert.ok(output.includes('piren.org www.piren.org {'));
  assert.ok(output.includes('  import acme'));
  assert.ok(output.includes('  reverse_proxy piren_app:3000'));
  assert.ok(output.includes('}'));
});

