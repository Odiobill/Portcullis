// ── TLS mode availability detection (P2) ─────────────────────────

console.log('\n# TLS mode availability detection');

test('availableTlsModes includes acme and internal always', () => {
  const modes = availableTlsModes();
  const acme = modes.find(m => m.value === 'acme');
  const internal = modes.find(m => m.value === 'internal');
  assert.ok(acme, 'acme should be present');
  assert.ok(internal, 'internal should be present');
  assert.equal(acme!.available, true, 'acme should always be available');
  assert.equal(internal!.available, true, 'internal should always be available');
});

test('availableTlsModes: namecheap available when env vars set', () => {
  const prevKey = process.env.NAMECHEAP_API_KEY;
  const prevUser = process.env.NAMECHEAP_API_USER;
  process.env.NAMECHEAP_API_KEY = 'test-key';
  process.env.NAMECHEAP_API_USER = 'test-user';
  try {
    const mode = availableTlsModes().find(m => m.value === 'namecheap_tls')!;
    assert.ok(mode);
    assert.equal(mode.available, true);
  } finally {
    process.env.NAMECHEAP_API_KEY = prevKey;
    process.env.NAMECHEAP_API_USER = prevUser;
  }
});

test('availableTlsModes: namecheap unavailable when env vars not set', () => {
  // Ensure env vars are not set
  const prevKey = process.env.NAMECHEAP_API_KEY;
  const prevUser = process.env.NAMECHEAP_API_USER;
  delete process.env.NAMECHEAP_API_KEY;
  delete process.env.NAMECHEAP_API_USER;
  try {
    const mode = availableTlsModes().find(m => m.value === 'namecheap_tls')!;
    assert.equal(mode.available, false);
  } finally {
    if (prevKey !== undefined) process.env.NAMECHEAP_API_KEY = prevKey;
    if (prevUser !== undefined) process.env.NAMECHEAP_API_USER = prevUser;
  }
});

